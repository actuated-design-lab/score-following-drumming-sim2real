def fig_hw_tasks(d, p2):
    """Hardware success rate per task and method: mean (bar) and the three runs (points), package values."""
    hw, runs = d["hw_task"], p2["runs"]
    fig, ax = plt.subplots(figsize=(DOUBLE, 2.2))
    w = 0.19
    marker = {"LSTM": "o", "MLP": "s", "FF": "^", "FF-cal": "D"}
    for j, m in enumerate(pkg.METHOD_ORDER):
        for i, t in enumerate(pkg.TASK_ORDER):
            r = hw[(hw.method == m) & (hw.task == t)].iloc[0]
            v = runs[(runs.method == m) & (runs.task == t)].success.values
            assert len(v) == 3 and abs(v.mean() - r.success_mean) < 6e-4, (m, t)
            x = i + (j - 1.5) * (w + 0.02)
            ax.bar(x, r.success_mean, width=w, color=COLOR[m], alpha=0.45, edgecolor="none",
                   label=m if i == 0 else None, zorder=2)
            ax.scatter([x] * 3, v, s=11, marker=marker[m], facecolor=COLOR[m], edgecolor="#0b0b0b",
                       linewidth=0.4, zorder=3)
    ax.set_xticks(range(len(pkg.TASK_ORDER)))
    ax.set_xticklabels(pkg.TASK_ORDER)
    ax.set_ylim(0, 1)
    ax.set_ylabel("Success rate")
    ax.yaxis.grid(True, color="#e4e3df", linewidth=0.5, zorder=0)
    ax.set_axisbelow(True)
    for s_ in ("top", "right"):
        ax.spines[s_].set_visible(False)
    ax.legend(ncol=4, frameon=False, loc="upper left", bbox_to_anchor=(0, 1.14), handlelength=1.2)
    fig.tight_layout()
    fig.savefig(FIG / "fig_hw_tasks.pdf")
    plt.close(fig)


OKUI_COLOR = {"A": "#eb6834", "B": "#7b4fb3"}   # part A, part B (the MLP policy plays both)


def fig_sss():
    """Reproduction of a human performance (2026-11-11): parts A and B, each in its own load-cell run (okui2026, second
    run of each part), on the shared time axis of the original performance; right axis: wrist and grip joint angles
    (data from okui_fig_data.py)."""
    from matplotlib.lines import Line2D
    st = pd.read_csv(DATA / "okui_sss_strikes.csv")
    fo = pd.read_csv(DATA / "okui_sss_force.csv")
    assert (st.part == "A").sum() == 32 and (st.part == "B").sum() == 19
    t0 = st.loc[st.part == "A", "target_s"].min()          # first onset of the original performance
    j_lo = min(fo.wrist_deg.min(), fo.grip_deg.min())      # same right-axis range in both rows, both joints
    j_hi = max(fo.wrist_deg.max(), fo.grip_deg.max())
    j_lim = (min(-6.0, j_lo - 3.0), max(62.0, j_hi + 3.0))
    F_STYLE = dict(color="#262523", linewidth=0.8)    # load-cell force: the main trace
    W_STYLE = dict(color="#9b9993", linewidth=0.4, linestyle="-")
    G_STYLE = dict(color="#b3b1aa", linewidth=0.4, linestyle=(0, (3.0, 1.6)))
    fig = plt.figure(figsize=(DOUBLE, 3.45))
    gs = fig.add_gridspec(4, 1, height_ratios=[0.28, 1.5, 0.28, 1.5], hspace=0.12)
    axes = {}
    for k, part in enumerate(("A", "B")):
        c = OKUI_COLOR[part]
        s = st[st.part == part]
        f = fo[fo.part == part]
        at = fig.add_subplot(gs[2 * k], sharex=axes.get("A_force"))
        af = fig.add_subplot(gs[2 * k + 1], sharex=at)
        axes[f"{part}_force"] = af
        at.vlines(s.target_s - t0, 0, 1.0, color=c, linewidth=0.9)
        at.set_ylim(0, 1.05); at.set_yticks([])
        at.set_ylabel(f"Part {part}\ntarget", rotation=0, ha="right", va="center", fontsize=7)
        for s_ in ("top", "right", "left", "bottom"):
            at.spines[s_].set_visible(False)
        at.tick_params(axis="x", bottom=False, labelbottom=False)
        af.plot(f.time_s - t0, f.force_N, zorder=1, **F_STYLE)
        aj = af.twinx()                                    # joint angles on the right axis, same samples as the force
        aj.plot(f.time_s - t0, f.wrist_deg, zorder=2, **W_STYLE)
        aj.plot(f.time_s - t0, f.grip_deg, zorder=2, **G_STYLE)
        aj.set_ylim(*j_lim)
        aj.set_yticks([0, 20, 40, 60])
        aj.set_ylabel("Joint angle (deg)")
        aj.spines["top"].set_visible(False)
        af.set_zorder(aj.get_zorder() + 1)
        af.patch.set_visible(False)
        hit = s.strike_s.notna()
        ok = hit & s.success.astype(bool)
        bad = hit & ~s.success.astype(bool)
        af.scatter(s.loc[ok, "strike_s"] - t0, s.loc[ok, "peak_force_N"], s=12, marker="o", facecolor=c,
                   edgecolor="#fcfcfb", linewidth=0.4, zorder=3)
        if bad.any():
            af.scatter(s.loc[bad, "strike_s"] - t0, s.loc[bad, "peak_force_N"], s=12, marker="o", facecolor="#fcfcfb",
                       edgecolor=c, linewidth=0.8, zorder=3)
        if (~hit).any():
            af.scatter(s.loc[~hit, "target_s"] - t0, [0] * int((~hit).sum()), s=14, marker="x", color="#52514e",
                       linewidth=0.8, zorder=3)
        af.set_ylim(-1, 46)
        af.set_yticks([0, 20, 40])
        af.set_ylabel("Force (N)")
        af.yaxis.grid(True, color="#e4e3df", linewidth=0.5)
        af.set_axisbelow(True)
        for s_ in ("top", "right"):
            af.spines[s_].set_visible(False)
        n_ok = int(ok.sum())
        af.text(1.0, 0.97, f"Part {part}: {n_ok} of {len(s)} onsets struck within $\\pm$30 ms (separate run)",
                transform=af.transAxes, ha="right", va="top", fontsize=7, color="#0b0b0b")
        if part == "A":
            af.tick_params(axis="x", labelbottom=False)
        else:
            af.set_xlabel("Time from the first onset of the original performance (s)")
    axes["A_force"].set_xlim(-0.2, 9.5)
    dot = dict(marker="o", linestyle="none", markersize=4.2, markeredgecolor="#fcfcfb", markeredgewidth=0.4)
    handles = [Line2D([], [], color=F_STYLE["color"], linewidth=1.2, label="Load-cell force (left axis)"),
               Line2D([], [], marker="o", linestyle="none", markersize=4.2, markerfacecolor=OKUI_COLOR["A"],
                      markeredgecolor="#fcfcfb", markeredgewidth=0.4, label="Part A strike within $\\pm$30 ms"),
               Line2D([], [], marker="o", linestyle="none", markersize=4.2, markerfacecolor=OKUI_COLOR["B"],
                      markeredgecolor="#fcfcfb", markeredgewidth=0.4, label="Part B strike within $\\pm$30 ms"),
               Line2D([], [], color=W_STYLE["color"], linewidth=1.2, linestyle="-", label="Wrist angle (right axis)"),
               Line2D([], [], color=G_STYLE["color"], linewidth=1.2, linestyle=(0, (3.0, 1.6)), label="Grip angle (right axis)")]
    fig.legend(handles=handles, ncol=5, frameon=False, loc="upper center", bbox_to_anchor=(0.5, 1.0),
               handlelength=1.8, columnspacing=1.2, fontsize=7)
    fig.subplots_adjust(left=0.09, right=0.93, top=0.92, bottom=0.11)
    fig.savefig(FIG / "fig_sss.pdf")
    plt.close(fig)


