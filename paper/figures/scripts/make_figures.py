# Fig. 2 (fig:fidelity): simulator versus hardware under identical open-loop commands (package 2, item 7).
# Inputs are data/fidelity_ts_<motion>.csv: the 10/05 hardware recording and the Gen2 simulation (no randomization)
# of the same command, aligned by the echo, every 5 ms. "simmeas" = simulation driven by the measured pressure,
# "simcfg" = simulation through the pressure model (+ 8 ms communication delay). Angles are in the hardware convention.
FID_MOTIONS = {  # panel: (file stem, time window in s or None for the DF triangle cycles, title)
    "a": ("tm_A_quasistatic", None, "(a) Quasi-static loop (DF triangle, 0.05 Hz)"),
    "b": ("tm_B_steps", (2.0, 37.0), "(b) Step response (DF steps)"),
    "c": ("tm_C_sine", (47.0, 68.0), "(c) Validation motion (DF sinusoids)"),
    "d": ("tm_E_dbl160_seed2", (2.0, 11.5), "(d) Strike motion (double strokes, 160 BPM)"),
}
FID_STYLE = {  # series: (label, color, linestyle, linewidth). Hardware leads; the two simulations are thinner.
    "real": ("Hardware", "#0b0b0b", "-", 1.1),
    "simmeas": ("Simulation, measured pressure", "#2a78d6", "-", 0.6),
    "simcfg": ("Simulation, pressure model", "#eb6834", (0, (6, 5)), 0.6),  # long gaps: stays distinct on the blue line
}
FID_Z = {"real": 2, "simmeas": 3, "simcfg": 4}  # drawing order: hardware at the bottom, the thin simulations on top
FID_CMD = dict(color="#8a8984", ls=":", lw=0.45, alpha=0.5)  # command in the pressure rows: kept below the measured line


def fig_fidelity():
    """Wrist angle of hardware and simulation for the four motions; DF pressure above panels (b)-(d)."""
    ts = {k: pd.read_csv(DATA / f"fidelity_ts_{m}.csv") for k, (m, _, _) in FID_MOTIONS.items()}
    fig = plt.figure(figsize=(DOUBLE, 4.6))
    outer = fig.add_gridspec(2, 2, left=0.08, right=0.99, top=0.84, bottom=0.085, wspace=0.27, hspace=0.42)

    def style(ax):
        ax.yaxis.grid(True, color="#e4e3df", linewidth=0.5)
        ax.set_axisbelow(True)
        for s_ in ("top", "right"):
            ax.spines[s_].set_visible(False)

    # (a) wrist angle against DF pressure over the two DF triangle cycles (2-42 s, the segment of the hysteresis loops).
    # Display only: 21-sample (105 ms) centred moving average of every series, the same smoothing as the loop widths
    # of Appendix D (porcaro_2026 analysis/eval/hys_loops.py), so that sensor noise does not hide the loop.
    d = ts["a"]
    seg = d[(d.time_s >= 2.0) & (d.time_s < 42.0)]
    cols = ["real_P_DF", "real_wrist_deg", "simmeas_wrist_deg", "simcfg_P_DF", "simcfg_wrist_deg"]
    seg = seg[cols].rolling(21, center=True).mean().dropna()
    ax = fig.add_subplot(outer[0, 0])
    for s_, x in (("real", seg.real_P_DF), ("simmeas", seg.real_P_DF), ("simcfg", seg.simcfg_P_DF)):
        lab, c, ls, lw = FID_STYLE[s_]
        ax.plot(x, seg[f"{s_}_wrist_deg"], color=c, ls=ls, lw=lw, label=lab, zorder=FID_Z[s_])
    ax.set_xlabel("DF pressure (MPa)")
    ax.set_ylabel("Wrist angle (deg)")
    ax.set_title(FID_MOTIONS["a"][2], fontsize=8, loc="left")
    style(ax)

    # (b)-(d) DF pressure (command, hardware, pressure model) above the wrist angle (three series)
    for k, pos in (("b", outer[0, 1]), ("c", outer[1, 0]), ("d", outer[1, 1])):
        d = ts[k]
        t0, t1 = FID_MOTIONS[k][1]
        w = d[(d.time_s >= t0) & (d.time_s <= t1)]
        inner = pos.subgridspec(2, 1, height_ratios=[1, 2.2], hspace=0.08)
        ap = fig.add_subplot(inner[0])
        aw = fig.add_subplot(inner[1], sharex=ap)
        ap.plot(w.time_s, w.cmd_DF, label="Command", zorder=1, **FID_CMD)
        for s_ in ("real", "simcfg"):
            lab, c, ls, lw = FID_STYLE[s_]
            ap.plot(w.time_s, w[f"{s_}_P_DF"], color=c, ls=ls, lw=lw, zorder=FID_Z[s_])
        ap.set_ylim(-0.02, 0.65)
        ap.set_yticks([0, 0.3, 0.6])
        ap.set_ylabel("$P_{\\mathrm{DF}}$\n(MPa)")
        ap.tick_params(labelbottom=False)
        ap.set_title(FID_MOTIONS[k][2], fontsize=8, loc="left")
        for s_ in ("real", "simmeas", "simcfg"):
            lab, c, ls, lw = FID_STYLE[s_]
            aw.plot(w.time_s, w[f"{s_}_wrist_deg"], color=c, ls=ls, lw=lw, zorder=FID_Z[s_])
        aw.set_xlim(t0, t1)
        aw.set_xlabel("Time (s)")
        aw.set_ylabel("Wrist angle (deg)")
        style(ap)
        style(aw)

    # Legend in two groups, one per kind of row, each led by its group name; a note explains the missing blue line.
    def line(s_):
        _, c, ls, lw = FID_STYLE[s_]
        return plt.Line2D([], [], color=c, ls=ls, lw=lw)

    groups = [
        ("Pressure rows:", [(line("real"), "Measured (hardware)"), (line("simcfg"), "Pressure model"),
                            (plt.Line2D([], [], color=FID_CMD["color"], ls=":", lw=0.8), "Command")]),
        ("Angle rows:", [(line(s_), FID_STYLE[s_][0]) for s_ in ("real", "simmeas", "simcfg")]),
    ]
    # One legend, 2 rows x 4 columns (column-major order): the first column holds the group names, so the columns align.
    blank = plt.Line2D([], [], ls="none")
    hs, ls_ = [blank, blank], [groups[0][0], groups[1][0]]
    for j in range(3):
        for _, items in groups:
            hs.append(items[j][0])
            ls_.append(items[j][1])
    leg = fig.legend(hs, ls_, ncol=4, frameon=False, loc="upper left", bbox_to_anchor=(0.005, 1.0), borderaxespad=0,
                     handlelength=2.2, columnspacing=1.0, handletextpad=0.5)
    for t in leg.get_texts()[:2]:
        t.set_fontweight("bold")
    # Note on its own line under the legend, starting at the second legend column.
    fig.canvas.draw()
    bb = leg.get_window_extent()
    x0 = fig.transFigure.inverted().transform(leg.legend_handles[2].get_window_extent().p0)[0]
    y0 = fig.transFigure.inverted().transform((0, bb.y0))[1]
    fig.text(x0, y0 - 0.006, "The simulation driven by the measured pressure is not drawn in the pressure rows, "
             "because its pressure is the measured pressure itself.", ha="left", va="top", fontsize=6.5,
             color="#52514e")
    fig.savefig(FIG / "fig_fidelity.pdf")
    plt.close(fig)


def fig_rl_curves():
    """Training curves of the two selected runs (appendix): mean episode reward per iteration (rsl_rl Train/mean_reward,
    stochastic actions), the reward upper bound of each curriculum level (all notes rewarded with R_match = 1, full rest
    bonus, no penalty), and the deterministic evaluation on the final training distribution at the last checkpoint.
    Sources: data/rl_curves.csv, rl_ceiling.csv, rl_train_dist.csv (porcaro_2026 PR #95 and the ceiling computation)."""
    cur = pd.read_csv(DATA / "rl_curves.csv")
    ceil = pd.read_csv(DATA / "rl_ceiling.csv")
    ev = pd.read_csv(DATA / "rl_train_dist.csv").set_index("method")
    fig, ax = plt.subplots(figsize=(SINGLE, 2.5))
    xs, ys = [], []
    for _, r in ceil.iterrows():
        xs += [r.iter_start, r.iter_end + 1]
        ys += [r.ceiling, r.ceiling]
    ax.plot(xs, ys, color="#52514e", lw=0.8, ls=(0, (4, 2.5)), label="Upper bound", zorder=2)
    for x in ceil.iter_start[1:]:
        ax.axvline(x, color="#c3c2b7", lw=0.5, zorder=1)
    for _, r in ceil.iterrows():
        ax.text((r.iter_start + r.iter_end + 1) / 2, r.ceiling + 1.5, f"level {int(r.level)}", ha="center", va="bottom",
                fontsize=6.5, color="#52514e")
    for m in ("MLP", "LSTM"):
        x = cur[cur.method == m].sort_values("iteration")
        ax.plot(x.iteration, x.mean_reward, color=COLOR[m], lw=0.8, label=f"{m} policy", zorder=3)
        e = ev.loc[m]
        ax.errorbar([1530], [e.return_mean], yerr=[e.return_sd], fmt="o", ms=3, color=COLOR[m], mec="#0b0b0b", mew=0.4,
                    elinewidth=0.7, capsize=1.5, zorder=4, clip_on=False)
    ax.axhline(0, color="#8a8984", lw=0.4, zorder=1)
    ax.set_xlim(0, 1560)
    ax.set_ylim(-40, 60)
    ax.set_xlabel("Training iteration")
    ax.set_ylabel("Mean episode reward")
    ax.yaxis.grid(True, color="#e4e3df", linewidth=0.5, zorder=0)
    ax.set_axisbelow(True)
    for s_ in ("top", "right"):
        ax.spines[s_].set_visible(False)
    h, l = ax.get_legend_handles_labels()
    h.append(plt.Line2D([], [], ls="none", marker="o", ms=3, color="#8a8984", mec="#0b0b0b", mew=0.4))
    l.append("Final evaluation (mean $\\pm$ SD)")
    ax.legend(h, l, ncol=2, frameon=False, loc="lower left", bbox_to_anchor=(-0.02, 1.0), fontsize=6.5,
              handlelength=1.6, columnspacing=0.8)
    fig.tight_layout()
    fig.savefig(FIG / "fig_rl_curves.pdf")
    plt.close(fig)


