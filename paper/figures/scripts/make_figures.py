    shw = d["sim_hw"].set_index("task")
    rows = []
    for m in ["LSTM", "MLP", "FF"]:
        rows.append([f"{m} (sim)"] + [f3(shw.loc[t, f"{m}_sim"]) for t in pkg.TASK_ORDER]
                    + [f3(shw.loc["Mean", f"{m}_sim"])])
    rows.append("MIDRULE")
    for m in pkg.METHOD_ORDER:
        if m == "FF-cal":
            rows.append("MIDRULE")
        cells = [m]
        for t in pkg.TASK_ORDER:
            r = hw[(hw.method == m) & (hw.task == t)].iloc[0]
            c = f"${f3(r.success_mean)}\\pm{f3(r.success_sd)}$"
            if r.success_old != r.success_mean:
                c += f" ({f3(r.success_old)})"
            cells.append(c)
        r = m5[m5.method == m].iloc[0]
