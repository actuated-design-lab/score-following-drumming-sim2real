def check_text(package_text):
    """Every three-decimal number in the results-related text must appear in the packages."""
    norm = package_text.replace("−", "-")
    known = set(re.findall(r"\d+\.\d{3}", norm))
    files = ["sections/03_system_model.tex", "sections/05_ff_baselines.tex", "sections/06_protocol.tex", "sections/07_results.tex",
             "sections/08_discussion.tex", "sections/09_conclusion.tex", "main.tex"]
    # Numbers from other records, stated here with their source so that the check stays exhaustive.
    other = {("sections/06_protocol.tex", "0.389"): "check motions (measured DF pressure), hardware record",
             ("sections/06_protocol.tex", "0.393"): "check motions (measured DF pressure), hardware record",
             ("sections/07_results.tex", "0.002"): "grip amplitude ratio on the sinusoid and strike-command replays (not used for identification), author's instruction 2026-11-10",
             ("sections/03_system_model.tex", "0.001"): "joint friction and grip viscosity (assumed values), research query answers 2026-11-10 item 1"}
    bad = []
    for f in files:
        for n in re.findall(r"(?<![\d.])\d+\.\d{3}(?!\d)", (PAPER / f).read_text(encoding="utf-8")):
            if n not in known and (f, n) not in other:
                bad.append((f, n))
    return bad


